/**
 * Pre-renders the large decorative SVGs to static markup so React does not have to hydrate
 * ~900 purely decorative nodes on first load. Source of truth stays in the JSX components.
 * Run: npm run gen:art
 */
import { writeFileSync } from "node:fs";
import { renderToStaticMarkup } from "react-dom/server";
import { ArtSprite } from "../src/components/ProductArt";
import { HeroArt, MapArt, Wheat } from "../src/components/Illustrations";

const wheatInner = renderToStaticMarkup(<Wheat />).replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
const wheatSymbol = `<symbol id="wheat" viewBox="0 0 40 160">${wheatInner}</symbol>`;
const wheatField = Array.from(
  { length: 22 },
  () => `<svg viewBox="0 0 40 160" aria-hidden="true" focusable="false"><use href="#wheat"></use></svg>`,
).join("");

const sprite = renderToStaticMarkup(<ArtSprite />).replace(/<\/svg>$/, `${wheatSymbol}</svg>`);

const out = {
  sprite,
  hero: renderToStaticMarkup(<HeroArt />),
  map: renderToStaticMarkup(<MapArt />),
  wheatField,
};

writeFileSync(
  new URL("../src/generated/art.ts", import.meta.url),
  `// Generated by scripts/gen-art.tsx. Do not edit by hand.\nexport const ART = ${JSON.stringify(out)} as const;\n`,
);
console.log(Object.entries(out).map(([k, v]) => `${k}: ${v.length} bytes`).join("\n"));
